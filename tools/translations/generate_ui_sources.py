#!/usr/bin/env python3
"""Generate ROM-free Java/C metadata from the reviewed interface manifest."""
import json
from pathlib import Path
from build_ptbr_patch import ROOT


def outputs(manifest):
    entries = manifest['entries']
    j = ['package com.dishii.zelda3;', '', '// Generated by tools/translations/generate_ui_sources.py; no ROM data.',
         'final class UiTranslationResources {',
         f"    static final int SIZE = {manifest['package_size']};",
         f"    static final long CRC = 0x{manifest['package_crc32']:08x}L;",
         f"    static final String SHA1 = \"{manifest['rom_sha1']}\";",
         '    // [resource ID, ROM offset, byte length]', '    static final int[][] ENTRIES = {']
    h = ['// Generated by tools/translations/generate_ui_sources.py; no ROM data.',
         '#pragma once', f"#define UI_PACKAGE_SIZE {manifest['package_size']}u",
         f"#define UI_PACKAGE_CRC 0x{manifest['package_crc32']:08x}u", 'enum {']
    for e in entries:
        name = e['name'][1:] if e['name'].startswith('k') else e['name']
        h.append(f"  kUi_{name} = {e['id']},")
        j.append(f"        {{{e['id']}, 0x{e['offset']:x}, {e['size']}}}, // {e['name']}")
    h += ['};', 'static const uint32 kUiResourceLayout[][3] = {']
    pos = 40 + 12 * len(entries)
    for e in entries:
        pos = (pos + 3) & ~3
        h.append(f"  {{{e['id']}, {pos}, {e['size']}}},")
        pos += e['size']
    assert pos + 4 == manifest['package_size']
    h += ['};', '']
    j += ['    };', '    private UiTranslationResources() {}', '}', '']
    return {'app/src/main/java/com/dishii/zelda3/UiTranslationResources.java':'\n'.join(j),
            'app/jni/src/src/ui_translation_data.h':'\n'.join(h)}


if __name__ == '__main__':
    manifest = json.loads(Path(__file__).with_name('ptbr_ui_manifest.json').read_text())
    for name, text in outputs(manifest).items():
        (ROOT / name).write_bytes(text.encode('utf8'))
